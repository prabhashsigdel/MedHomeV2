/** Manual dependency graph, created once per process by [MedHomeApplication]. */
class AppContainer(context: Context) {
    private val appScope = CoroutineScope(SupervisorJob() + Dispatchers.Main.immediate)

    val credentialClient: CredentialClient = CredentialManagerClient(
        appContext = context.applicationContext,
        // Generated by the google-services plugin from google-services.json.
        webClientId = context.getString(R.string.default_web_client_id),
    )

    /** Every open Firestore listener; sign-out stops them before shutting Firestore down. */
    private val listeners = ListenerRegistry()

    private val authDataSource = FirebaseAuthDataSource(FirebaseAuth.getInstance())

    val sessionManager = SessionManager(
        auth = authDataSource,
        profiles = FirestoreProfileStore { FirebaseFirestore.getInstance() },
        credentials = credentialClient,
        scope = appScope,
        listeners = listeners,
        clearReminders = { reminderEngine.wipe() },
        cancelUpcomingBookings = { asAuthFailure { bookingRepository.cancelAllUpcoming() } },
        eraseBookingNames = { asAuthFailure { bookingRepository.erasePatientName() } },
    )

    /** Account deletion reports [AuthException]s: a booking step's failure becomes one. */
    private suspend fun asAuthFailure(block: suspend () -> Unit) {
        try {
            block()
        } catch (e: BookingException) {
            val error = if (e.error == BookingError.NETWORK) AuthError.NETWORK else AuthError.UNKNOWN
            throw AuthException(error, e)
        }
    }

    val passwordSaveOffers = PasswordSaveOffers(SharedPrefsSavePromptHistory(context))

    val savedAccountsPrompt = SavedAccountsPrompt()

    val themeSettings = DataStoreThemeSettings(context)

    val doctorRepository: DoctorRepository = FirestoreDoctorRepository({ FirebaseFirestore.getInstance() }, listeners)

    /** Booking and cancelling also set and remove the appointment's reminders at once. */
    val bookingRepository: BookingRepository = RemindingBookingRepository(
        delegate = FirestoreBookingRepository(
            firestore = { FirebaseFirestore.getInstance() },
            currentUid = { authDataSource.currentUser?.uid },
            verifiedClaim = authDataSource::emailVerifiedClaim,
            listeners = listeners,
        ),
        onBooked = { id, startAtMillis -> reminderEngine.addAppointment(id, startAtMillis, doctorName = "") },
        onCancelled = { id -> reminderEngine.removeAppointment(id) },
    )

    /** Receivers' work: off the main thread, and not tied to any screen. */
    val backgroundScope = CoroutineScope(SupervisorJob() + Dispatchers.Default)

    val reminderSettings: ReminderSettings = DataStoreReminderSettings(context)

    /** Opened on first use (a receiver may be the first thing to need it). */
    private val reminderDatabase by lazy { ReminderDatabase.create(context) }

    /** Medicine and appointment reminders: local only (Room), wiped on sign-out. */
    val reminderEngine: ReminderEngine by lazy {
        ReminderEngine(
            dao = reminderDatabase.reminderDao(),
            settings = reminderSettings,
            scheduler = AndroidAlarmScheduler(context),
            notifier = AndroidReminderNotifier(context),
            currentPatientUid = {
                (sessionManager.state.value as? SessionState.SignedIn)?.profile?.takeIf { it.role == Role.PATIENT }?.uid
            },
            accountUid = { authDataSource.currentUser?.uid },
        )
    }

    val appointmentReminderSync = AppointmentReminderSync(
        session = sessionManager.state,
        bookings = bookingRepository,
        apply = { uid, snapshot -> reminderEngine.syncAppointments(uid, snapshot.bookings, snapshot.fromCache) },
        scope = appScope,
        // Another account's reminders, left by a failed sign-out wipe, go before this one's sync.
        claimOwner = { uid -> reminderEngine.claim(uid) },
    )

    /** Only admins' screens use it; the rules refuse everyone else. */
    val adminRepository: AdminRepository = FirestoreAdminRepository(
        firestore = { FirebaseFirestore.getInstance() },
        currentUid = { authDataSource.currentUser?.uid },
        listeners = listeners,
    )
}

val CreationExtras.appContainer: AppContainer
    get() = (checkNotNull(this[APPLICATION_KEY]) as MedHomeApplication).container
